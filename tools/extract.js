/* Builds js/content.js from the decision tool's data.js: only what the decision room needs
   (priorities, levels, criteria, option names and scores, the recommendation). Usage:
   node tools/extract.js path/to/data.js > js/content.js */
const fs = require("fs"), vm = require("vm");
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(process.argv[2], "utf8"), ctx);
const HC = ctx.window.HC;
const scores = {};
Object.keys(HC.scores).forEach(o => { scores[o] = {}; Object.keys(HC.scores[o]).forEach(c => { scores[o][c] = HC.scores[o][c][0]; }); });
const out = {
  client: HC.meta.client,
  levelPoints: HC.levelPoints,
  levelNames: HC.levelNames,
  principles: HC.principles.map(p => ({ id: p.id, name: p.name, q: p.q, criteria: p.criteria, def: p.def, invert: !!p.invert, levels: p.levels.map(l => ({ id: l.id, name: l.name, text: l.text })) })),
  criteria: HC.criteria.map(c => ({ id: c.id, name: c.name })),
  options: HC.options.map(o => ({ id: o.id, name: o.name, idea: o.idea })),
  scores: scores,
  recommendation: { option: HC.recommendation.option, headline: HC.recommendation.headline },
  ambitions: HC.ambitions.map(a => ({ id: a.id, name: a.name, choices: a.choices }))
};
process.stdout.write("/* Generated by tools/extract.js from the decision tool's data. Synthetic data for a fictional client. */\nwindow.HC = " + JSON.stringify(out, null, 1) + ";\n");
